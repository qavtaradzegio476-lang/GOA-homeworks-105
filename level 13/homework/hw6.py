
# მომხმარებელს შეაყვანინეთ რიცხვები. თუ მომხმარებელი შეიყვანს უარყოფით რიცხვს, გამოიყენეთ break.
#  დადებითი რიცხვები დაამატეთ total ცვლადში და ბოლოს გამოიტანეთ ჯამი.


total = 0

while True:
    number = int(input("შეიყვანეთ რიცხვი: "))

    if number < 0:
        break

    total += number

print("ჯამი:", total)