#  მომხმარებელს შემოატანინეთ ორი რიცხვი და Nested while loop-ის გამოყენებით შექმენით ვარსკვლავების მართკუთხედი,
#  სადაც პირველი რიცხვი იქნება სტრიქონების რაოდენობა, ხოლო მეორე — თითოეულ
#  სტრიქონში ვარსკვლავების რაოდენობა. 

rows = int(input("შეიყვანეთ სტრიქონების რაოდენობა: "))
columns = int(input("შეიყვანეთ ვარსკვლავების რაოდენობა: "))

i = 0

while i < rows:
    j = 0

    while j < columns:
        print("*", end="")
        j += 1

    print()
    i += 1